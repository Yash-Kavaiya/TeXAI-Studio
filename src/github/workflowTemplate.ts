import { dirname } from '../utils/paths'

const basename = (path: string) => path.slice(path.lastIndexOf('/') + 1)

export const WORKFLOW_PATH = '.github/workflows/build-pdf.yml'

const LATEX_GITIGNORE = `# LaTeX build output
*.aux
*.bbl
*.blg
*.fdb_latexmk
*.fls
*.log
*.out
*.synctex.gz
*.toc
*.lof
*.lot
*.nav
*.snm
*.vrb
`

export function latexGitignore(): string {
  return LATEX_GITIGNORE
}

/** Joins non-empty path segments with '/'. */
export function joinPath(...parts: string[]): string {
  return parts.filter(Boolean).join('/')
}

/** Where CI (and an optional committed copy) puts the compiled PDF, repo-relative. */
export function pdfOutputPath(rootFile: string, dir: string): string {
  return joinPath(dir, rootFile.replace(/\.tex$/i, '') + '.pdf')
}

function yamlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

/**
 * A GitHub Actions workflow that builds the project's PDF with latexmk on every
 * push and pull request, uploads it as a build artifact, and — when a `v*` tag
 * is pushed — publishes it on a GitHub Release (the project's "final PDF").
 *
 * `dir` is the folder inside the repo that holds the project ('' for the root).
 */
export function buildPdfWorkflow({ rootFile, dir, branch }: { rootFile: string; dir: string; branch: string }): string {
  const workDir = joinPath(dir, dirname(rootFile)) || '.'
  const rootName = basename(rootFile)
  const pdf = pdfOutputPath(rootFile, dir)
  const pathFilter = dir ? `\n    paths:\n      - ${yamlString(`${dir}/**`)}\n      - ${yamlString(WORKFLOW_PATH)}` : ''

  return `# Generated by TeXAI-Studio. Builds the PDF on every push and pull request;
# push a tag like v1.0 to publish the PDF on a GitHub Release.
name: Build PDF

on:
  push:
    branches: [${yamlString(branch)}]
    tags: ['v*']${pathFilter}
  pull_request:${pathFilter}
  workflow_dispatch:

concurrency:
  group: build-pdf-\${{ github.ref }}
  cancel-in-progress: true

permissions:
  contents: write

jobs:
  build:
    name: Compile LaTeX
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - uses: actions/checkout@v4

      - name: Compile with latexmk
        uses: xu-cheng/latex-action@v3
        with:
          root_file: ${yamlString(rootName)}
          working_directory: ${yamlString(workDir)}

      - name: Upload PDF artifact
        uses: actions/upload-artifact@v4
        with:
          name: pdf
          path: ${yamlString(pdf)}
          if-no-files-found: error

      - name: Publish release
        if: startsWith(github.ref, 'refs/tags/v')
        uses: softprops/action-gh-release@v2
        with:
          files: ${yamlString(pdf)}
          generate_release_notes: true
`
}
